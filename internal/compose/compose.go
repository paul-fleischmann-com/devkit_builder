// Package compose renders the Containerfile of a devkit: a base image plus
// features, in the order of the kit file. It only produces text.
package compose

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

var (
	namePattern     = regexp.MustCompile(`^[a-z0-9]([a-z0-9-]{0,40}[a-z0-9])?$`)
	snapshotPattern = regexp.MustCompile(`^[0-9]{8}T[0-9]{6}Z$`)
	digestPattern   = regexp.MustCompile(`^.+@sha256:[0-9a-f]{64}$`)
	optionPattern   = regexp.MustCompile(`^[a-z][a-z0-9_]{0,30}$`)
)

// KitError means the kit or one of its features is not usable; the message says why.
type KitError struct{ Msg string }

func (e *KitError) Error() string { return e.Msg }

func errf(format string, a ...any) error { return &KitError{Msg: fmt.Sprintf(format, a...)} }

func load(path string) (map[string]any, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, errf("%s: not readable as JSON (%v)", filepath.Base(path), err)
	}
	var v any
	if err := json.Unmarshal(data, &v); err != nil {
		return nil, errf("%s: not readable as JSON (%v)", filepath.Base(path), err)
	}
	obj, ok := v.(map[string]any)
	if !ok {
		return nil, errf("%s: must be a JSON object", filepath.Base(path))
	}
	return obj, nil
}

func str(v any) string {
	s, _ := v.(string)
	return s
}

// DigestOf is one sha256 over the names and contents of the files of a directory (stable order).
func DigestOf(dir string) (string, error) {
	h := sha256.New()
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, err := filepath.Rel(dir, p)
		if err != nil {
			return err
		}
		data, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		h.Write([]byte(filepath.ToSlash(rel)))
		h.Write([]byte{0})
		h.Write(data)
		h.Write([]byte{0})
		return nil
	})
	return hex.EncodeToString(h.Sum(nil)), err
}

// CheckFeature validates features/<id> below root and returns its feature.json.
func CheckFeature(root, id string) (map[string]any, error) {
	if !namePattern.MatchString(id) {
		return nil, errf("feature name %q: a-z, 0-9 and - only", id)
	}
	dir := filepath.Join(root, "features", id)
	if st, err := os.Stat(filepath.Join(dir, "install.sh")); err != nil || !st.Mode().IsRegular() {
		return nil, errf("feature %s: no install.sh", id)
	}
	meta, err := load(filepath.Join(dir, "feature.json"))
	if err != nil {
		return nil, err
	}
	if got := meta["id"]; got != id {
		return nil, errf("feature %s: feature.json names another id (%v)", id, got)
	}
	if opts, present := meta["options"]; present {
		m, ok := opts.(map[string]any)
		if !ok {
			return nil, errf("feature %s: options must be an object with lower case names", id)
		}
		for name := range m {
			if !optionPattern.MatchString(name) {
				return nil, errf("feature %s: options must be an object with lower case names", id)
			}
		}
	}
	return meta, nil
}

// LoadKit validates kits/<kit>.json and base.json below root; it returns the base image,
// the kit spec and the feature ids.
func LoadKit(root, kit string) (image string, spec map[string]any, ids []string, err error) {
	if !namePattern.MatchString(kit) {
		return "", nil, nil, errf("kit name %q: a-z, 0-9 and - only", kit)
	}
	base, err := load(filepath.Join(root, "base.json"))
	if err != nil {
		return "", nil, nil, err
	}
	image = str(base["image"])
	if !digestPattern.MatchString(image) {
		return "", nil, nil, errf("base.json: the image must be given by digest (name@sha256:...)")
	}
	spec, err = load(filepath.Join(root, "kits", kit+".json"))
	if err != nil {
		return "", nil, nil, err
	}
	if !snapshotPattern.MatchString(str(spec["apt_snapshot"])) {
		return "", nil, nil, errf("kit %s: apt_snapshot must look like 20261019T000000Z", kit)
	}
	list, ok := spec["features"].([]any)
	seen := map[string]bool{}
	valid := ok && len(list) > 0
	for _, item := range list {
		s, isStr := item.(string)
		if !isStr || seen[s] {
			valid = false
			break
		}
		seen[s] = true
		ids = append(ids, s)
	}
	if !valid {
		return "", nil, nil, errf("kit %s: features must be a non-empty list without duplicates", kit)
	}
	for _, id := range ids {
		if _, err := CheckFeature(root, id); err != nil {
			return "", nil, nil, err
		}
	}
	return image, spec, ids, nil
}

// Compose returns the Containerfile of kit. commit, if set, is recorded as a label.
func Compose(root, kit, commit string) (string, error) {
	image, spec, ids, err := LoadKit(root, kit)
	if err != nil {
		return "", err
	}
	snapshot := str(spec["apt_snapshot"])
	description := strings.Join(strings.Fields(str(spec["description"])), " ")

	lines := []string{
		strings.TrimRight("# Devkit "+kit+": "+description, " "),
		"# Generated by devkit compose; do not edit. Build context: the root of the devkits repository.",
		"FROM " + image,
		"ENV DEBIAN_FRONTEND=noninteractive",
		`RUN rm -f /etc/apt/sources.list /etc/apt/sources.list.d/* \`,
		`    && printf 'Types: deb\nURIs: http://snapshot.debian.org/archive/debian/%s/\nSuites: trixie\nComponents: main\nSigned-By: /usr/share/keyrings/debian-archive-keyring.pgp\nCheck-Valid-Until: no\n' ` +
			"'" + snapshot + "' > /etc/apt/sources.list.d/snapshot.sources",
	}
	labels := [][2]string{
		{"org.opencontainers.image.title", "devkit-" + kit},
		{"devkit.kit", kit},
		{"devkit.apt_snapshot", snapshot},
	}
	for _, id := range ids {
		digest, err := DigestOf(filepath.Join(root, "features", id))
		if err != nil {
			return "", err
		}
		labels = append(labels, [2]string{"devkit.feature." + id, digest[:16]})
		lines = append(lines,
			fmt.Sprintf("COPY features/%s/ /tmp/devkit/%s/", id, id),
			fmt.Sprintf(`RUN cd /tmp/devkit/%s && bash ./install.sh \`, id),
			fmt.Sprintf("    && rm -rf /tmp/devkit/%s /var/lib/apt/lists/*", id),
		)
	}
	if commit != "" {
		labels = append(labels, [2]string{"devkit.commit", commit})
	}
	pairs := make([]string, len(labels))
	for i, l := range labels {
		pairs[i] = fmt.Sprintf(`%s="%s"`, l[0], l[1])
	}
	lines = append(lines,
		`RUN find / -xdev -type f -perm /6000 -exec chmod a-s {} + \`,
		`    && test -z "$(find / -xdev -type f -perm /6000)"`,
		"RUN useradd --uid 1000 --user-group --create-home --home-dir /home/worker --shell /usr/sbin/nologin worker",
		"ENV HOME=/home/worker PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1",
		"LABEL "+strings.Join(pairs, " \\\n      "),
		"USER 1000:1000",
		"WORKDIR /",
	)
	return strings.Join(lines, "\n") + "\n", nil
}

// Kits lists the kit names (kits/*.json) below root, sorted.
func Kits(root string) ([]string, error) {
	return names(filepath.Join(root, "kits"), func(e fs.DirEntry) (string, bool) {
		n := e.Name()
		return strings.TrimSuffix(n, ".json"), !e.IsDir() && strings.HasSuffix(n, ".json")
	})
}

// Features lists the feature ids (directories in features/) below root, sorted.
func Features(root string) ([]string, error) {
	return names(filepath.Join(root, "features"), func(e fs.DirEntry) (string, bool) {
		return e.Name(), e.IsDir()
	})
}

func names(dir string, pick func(fs.DirEntry) (string, bool)) ([]string, error) {
	entries, err := os.ReadDir(dir) // sorted by name
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range entries {
		if n, ok := pick(e); ok {
			out = append(out, n)
		}
	}
	return out, nil
}
