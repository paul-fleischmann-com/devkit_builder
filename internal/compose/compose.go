package compose

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var (
	nameRe = regexp.MustCompile(`^[a-z0-9]([a-z0-9-]{0,40}[a-z0-9])?$`)
	snapshotRe = regexp.MustCompile(`^\d{8}T\d{6}Z$`)
	digestRe = regexp.MustCompile(`.+@sha256:[0-9a-f]{64}$`)
	optionRe = regexp.MustCompile(`^[a-z][a-z0-9_]{0,30}$`)
)

type KitError string
func (e KitError) Error() string { return string(e) }

type FeatureMeta struct {
	ID string `json:"id"`
	Description string `json:"description"`
	Options map[string]any `json:"options"`
}

func load(path string) (map[string]any, error) {
	b, err := os.ReadFile(path)
	if err != nil { return nil, KitError(filepath.Base(path)+": not readable as JSON") }
	var m map[string]any
	if err := json.Unmarshal(b,&m); err != nil { return nil, err }
	return m,nil
}

func digestOf(dir string) (string,error){
	h:=sha256.New(); var files []string
	err:=filepath.Walk(dir, func(path string, info os.FileInfo, err error) error {
		if err!=nil{return err}; if !info.IsDir(){files=append(files,path)}; return nil
	})
	if err!=nil{return "",err}
	sort.Strings(files)
	for _,p:= range files {
		rel,_:=filepath.Rel(dir,p)
		b,_:=os.ReadFile(p)
		h.Write([]byte(rel)); h.Write([]byte{0}); h.Write(b); h.Write([]byte{0})
	}
	return hex.EncodeToString(h.Sum(nil)),nil
}

func validateFeature(root,id string) error {
	if !nameRe.MatchString(id){ return KitError("feature name invalid") }
	d:=filepath.Join(root,"features",id)
	if _,err:=os.Stat(filepath.Join(d,"install.sh")); err!=nil { return KitError(fmt.Sprintf("feature %s: no install.sh",id)) }
	b,err:=os.ReadFile(filepath.Join(d,"feature.json")); if err!=nil { return err }
	var m FeatureMeta
	if err:=json.Unmarshal(b,&m); err!=nil { return err }
	if m.ID!=id { return KitError("feature.json names another id") }
	for k:= range m.Options { if !optionRe.MatchString(k){ return KitError("invalid option")}}
	return nil
}

func Compose(root, kit, commit string)(string,error){
	if !nameRe.MatchString(kit){ return "", KitError("invalid kit name") }
	base,err:=load(filepath.Join(root,"base.json")); if err!=nil{return "",err}
	image:=fmt.Sprint(base["image"])
	if !digestRe.MatchString(image){ return "", KitError("base image must use digest") }
	ks,err:=load(filepath.Join(root,"kits",kit+".json")); if err!=nil{return "",err}
	snapshot:=fmt.Sprint(ks["apt_snapshot"])
	if !snapshotRe.MatchString(snapshot){ return "", KitError("invalid snapshot") }
	arr,ok:=ks["features"].([]any); if !ok || len(arr)==0 { return "", KitError("features required") }
	seen:=map[string]bool{}
	ids:=[]string{}
	for _,v:= range arr { s:=fmt.Sprint(v); if seen[s]{return "",KitError("duplicate feature")}; seen[s]=true; ids=append(ids,s); if err:=validateFeature(root,s); err!=nil{return "",err}}
	lines:=[]string{
		fmt.Sprintf("# Devkit %s: %v",kit,ks["description"]),
		"# Generated by devkit compose",
		fmt.Sprintf("FROM %s",image),
		"ENV DEBIAN_FRONTEND=noninteractive",
	}
	labels:=map[string]string{"org.opencontainers.image.title":"devkit-"+kit,"devkit.kit":kit,"devkit.apt_snapshot":snapshot}
	for _,id:= range ids {
		dg,_:=digestOf(filepath.Join(root,"features",id))
		labels["devkit.feature."+id]=dg[:16]
		lines=append(lines,
			fmt.Sprintf("COPY features/%s/ /tmp/devkit/%s/",id,id),
			fmt.Sprintf("RUN cd /tmp/devkit/%s && bash ./install.sh && rm -rf /tmp/devkit/%s /var/lib/apt/lists/*",id,id))
	}
	if commit!="" { labels["devkit.commit"]=commit }
	lines=append(lines,
		"RUN find / -xdev -type f -perm /6000 -exec chmod a-s {} +",
		"RUN useradd --uid 1000 --user-group --create-home --home-dir /home/worker --shell /usr/sbin/nologin worker",
		"ENV HOME=/home/worker PYTHONDONTWRITEBYTECODE=1 PYTHONUNBUFFERED=1")
	var lbl []string
	for k,v:= range labels { lbl=append(lbl, fmt.Sprintf("%s=\"%s\"",k,v)) }
	sort.Strings(lbl)
	lines=append(lines,"LABEL "+strings.Join(lbl," \\\n      "),"USER 1000:1000","WORKDIR /")
	return strings.Join(lines,"\n")+"\n",nil
}
